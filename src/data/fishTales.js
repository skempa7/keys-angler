// Stable within a day, rotates day to day.
export function taleOfTheDay(date = new Date()) {
  if (!TALES.length) return null
  const start = new Date(date.getFullYear(), 0, 0)
  const doy = Math.floor((date - start) / 86400000)
  return TALES[doy % TALES.length]
}

export function talesByCategory() {
  const map = {}
  for (const t of TALES) (map[t.category] = map[t.category] || []).push(t)
  return CAT_ORDER.filter((c) => map[c] && map[c].length).map((c) => ({ key: c, label: CATEGORIES[c] || c, items: map[c] }))
}
